#!/bin/bash
# Lighting-regime switch: decides whether the detector should run its DAY or NIGHT
# thresholds, writes ~/.ojogato/profile.env, and restarts the detector only when the
# regime actually changed. Called every cycle by heartbeat.sh; also runnable by hand
# (`motion-profile.sh --print` shows the decision without touching anything).
#
# Why luma and not a clock (OJOGATO_PROFILE_MODE=auto, the default):
#   The detector does not care what time it is — it cares how much light the sensor has.
#   At ~11/255 the webcam runs at max gain and the frame is mostly grain, which mpdecimate
#   scores as change; at ~43/255 the same room is quiet. Those two regimes do not line up
#   with sunset: a lamp left on at 22:00 is the DAY regime (measured 2026-08-09, the 21:22
#   person event read as a normal lit scene), and a shuttered room at 15:00 is the NIGHT one.
#   A clock would have picked the wrong profile in both cases. Set OJOGATO_PROFILE_MODE=schedule
#   if you want the clock anyway, or day/night to pin one, or off to disable switching.
#
# Hysteresis is not optional: a single threshold flaps at dusk, and every flap restarts the
# detector. NIGHT is entered below DARK_YAVG, DAY only above LIT_YAVG, and readings between
# the two change nothing.
OJOGATO_HOME="${OJOGATO_HOME:-$HOME/.ojogato}"
source "$OJOGATO_HOME/config.env"

PROFILE_ENV="$OJOGATO_HOME/profile.env"
ALIVE="$OJOGATO_HOME/frames/detector-alive.jpg"
MODE="${OJOGATO_PROFILE_MODE:-auto}"
DARK="${OJOGATO_DARK_YAVG:-16}"
LIT="${OJOGATO_LIT_YAVG:-24}"
PRINT_ONLY=false
[ "$1" = "--print" ] && PRINT_ONLY=true

FFMPEG="$OJOGATO_HOME/bin/ffmpeg"
[ -x "$FFMPEG" ] || FFMPEG="$(command -v ffmpeg)"

CURRENT=""
[ -f "$PROFILE_ENV" ] && CURRENT=$(grep -oE '^OJOGATO_ACTIVE_PROFILE="[a-z]+"' "$PROFILE_ENV" | cut -d'"' -f2)

yavg_of() {  # $1 = image or video file -> mean luma 0-255, empty on failure
  [ -s "$1" ] || return 1
  "$FFMPEG" -v error -i "$1" -vf "signalstats,metadata=print:key=lavfi.signalstats.YAVG:file=-" \
    -frames:v 1 -f null - 2>/dev/null | grep -o 'YAVG=[0-9.]*' | cut -d= -f2 | head -1
}

# --- measure -----------------------------------------------------------------
# Prefer the detector's own liveness frame: it is already being written every
# OJOGATO_DETECTOR_ALIVE_SEC and costs nothing. Only open a second RTSP session if that
# frame is missing or stale (detector down — heartbeat.sh handles that separately).
YAVG=""; SRC=""
if [ -s "$ALIVE" ]; then
  AGE=$(( $(date +%s) - $(stat -f %m "$ALIVE") ))
  if [ "$AGE" -le $(( ${OJOGATO_DETECTOR_ALIVE_SEC:-30} * 4 )) ]; then
    YAVG=$(yavg_of "$ALIVE"); SRC="detector-alive.jpg"
  fi
fi
if [ -z "$YAVG" ]; then
  TMP="$OJOGATO_HOME/frames/.profile-probe.jpg"
  "$FFMPEG" -y -v error -rtsp_transport tcp -i rtsp://127.0.0.1:8554/cam \
    -frames:v 1 -q:v 6 -update 1 "$TMP" 2>/dev/null
  YAVG=$(yavg_of "$TMP"); SRC="live probe"
  rm -f "$TMP"
fi

# --- decide ------------------------------------------------------------------
HOUR=$((10#$(date +%H)))
case "$MODE" in
  off)   [ "$PRINT_ONLY" = true ] && echo "profile switching disabled (OJOGATO_PROFILE_MODE=off)"; exit 0 ;;
  day|night) WANT="$MODE" ;;
  schedule)
    if [ "$HOUR" -ge "${OJOGATO_DAY_START:-8}" ] && [ "$HOUR" -le "${OJOGATO_DAY_END:-23}" ]
      then WANT="day"; else WANT="night"; fi ;;
  *)
    if [ -z "$YAVG" ]; then
      # Could not measure. Changing profile on no evidence is worse than leaving it alone.
      [ "$PRINT_ONLY" = true ] && echo "no luma reading — keeping ${CURRENT:-day}"
      exit 0
    fi
    if   awk "BEGIN{exit !($YAVG <  $DARK)}"; then WANT="night"
    elif awk "BEGIN{exit !($YAVG >  $LIT)}";  then WANT="day"
    else WANT="${CURRENT:-day}"   # inside the hysteresis band: hold
    fi ;;
esac

if [ "$PRINT_ONLY" = true ]; then
  echo "mode=$MODE luma=${YAVG:-n/a} (via ${SRC:-none}) dark<$DARK lit>$LIT current=${CURRENT:-none} -> $WANT"
  exit 0
fi

# --- apply -------------------------------------------------------------------
if [ "$WANT" = "night" ]; then
  HI="${OJOGATO_NIGHT_MOTION_HI:-72}"; LO="${OJOGATO_NIGHT_MOTION_LO:-36}"
  FRAC="${OJOGATO_NIGHT_MOTION_FRAC:-0.6}"
  PRE="${OJOGATO_NIGHT_MOTION_PREFILTER:-${OJOGATO_MOTION_PREFILTER:-deflicker=size=5:mode=am}}"
else
  HI="${OJOGATO_MOTION_HI:-48}"; LO="${OJOGATO_MOTION_LO:-24}"
  FRAC="${OJOGATO_MOTION_FRAC:-0.6}"
  PRE="${OJOGATO_MOTION_PREFILTER:-deflicker=size=5:mode=am}"
fi

cat > "$PROFILE_ENV" <<EOF
# Generated by motion-profile.sh — do not edit; edit config.env instead.
# Sourced by motion-run.sh AFTER config.env, so these win for the current regime.
OJOGATO_ACTIVE_PROFILE="$WANT"
OJOGATO_PROFILE_YAVG="${YAVG:-}"
OJOGATO_PROFILE_AT="$(date '+%Y-%m-%d %H:%M:%S')"
OJOGATO_MOTION_HI="$HI"
OJOGATO_MOTION_LO="$LO"
OJOGATO_MOTION_FRAC="$FRAC"
OJOGATO_MOTION_PREFILTER="$PRE"
EOF

[ "$WANT" = "$CURRENT" ] && exit 0

# Regime changed — the detector reads its thresholds once at startup, so it has to be
# restarted to pick them up. kickstart -k is a stop+start of just this job; the publisher
# and recorder are untouched, so no stream-restart race is opened.
echo "$(date '+%Y-%m-%d %H:%M:%S') profile ${CURRENT:-none} -> $WANT (luma=${YAVG:-n/a}, hi=$HI lo=$LO)" \
  >> "$OJOGATO_HOME/logs/profile.log"
launchctl kickstart -k "gui/$(id -u)/com.ojogato.motion" 2>/dev/null
